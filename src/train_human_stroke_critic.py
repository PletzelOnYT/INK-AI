#!/usr/bin/env python3
"""Train an actual neural HUMAN-stroke critic using UJI writer-labelled ink.

Positive examples are real unfinished-letter suffixes from pen recordings.
Negatives are broken straight/overlong trajectories and poor trajectories
generated by INK AI's CURRENT GRU. No example strokes ship in the model.
Unseen writers determine whether this critic may be released.
"""
import argparse,json,math,random
from pathlib import Path
import numpy as np
import torch
from torch import nn
from train import CHARS,SEED
from train_stroke_sequence import Strokes,fetch_uji,parse_uji
from train_stroke_sequence_v2 import load_published
from train_prefix_domain_v2 import prefix_frame
from train_prefix_completion import modal_token

def features(prefix,paths):
    coordinates=np.cumsum(np.asarray(prefix)[:,:2],axis=0)
    pos=coordinates[-1];allpts=np.asarray([p for path in paths for p in path])
    if not len(allpts):return np.zeros(16,np.float32)
    first,last=allpts[0],allpts[-1]
    length=turns=up=down=maxjump=0.;steps=0;straight=0.
    for path in paths:
        p=np.asarray(path,np.float64)
        if len(p)<2:continue
        diff=np.diff(p,axis=0);norm=np.linalg.norm(diff,axis=1)
        travel=float(norm.sum());length+=travel;steps+=len(norm)
        maxjump=max(maxjump,float(norm.max()))
        up+=float(np.maximum(-diff[:,1],0).sum())
        down+=float(np.maximum(diff[:,1],0).sum())
        if travel>.02:straight=max(straight,float(np.linalg.norm(p[-1]-p[0])/travel))
        for i in range(1,len(diff)):
            a,b=diff[i-1],diff[i]
            if np.linalg.norm(a)>.003 and np.linalg.norm(b)>.003:
                turns+=abs(math.atan2(a[0]*b[1]-a[1]*b[0],a@b))/math.pi
    box=np.ptp(coordinates,axis=0);span=np.ptp(allpts,axis=0)
    x=[last[0]-first[0],last[1]-first[1],length,straight,maxjump,
       turns/max(1,steps),len(paths)/4.,float(np.linalg.norm(first-pos)),
       span[0],span[1],box[0],box[1],allpts[:,1].min()-pos[1],
       allpts[:,1].max()-pos[1],up/max(.02,length),down/max(.02,length)]
    return np.asarray([float(np.clip(v,-2,2)) for v in x],np.float32)

def paths_from_tokens(prefix,tokens):
    pos=np.asarray(prefix)[:,:2].sum(axis=0).copy()
    result=[];active=[pos.tolist()]
    for dx,dy,draw in tokens:
        pos=pos+[dx,dy]
        if draw>.5:active.append(pos.tolist())
        else:
            if len(active)>1:result.append(active)
            active=[pos.tolist()]
    if len(active)>1:result.append(active)
    return result

@torch.no_grad()
def generate_bad(model,prefix,label):
    inputs=torch.from_numpy(prefix[None].astype(np.float32))
    label=torch.tensor([label])
    emb=model.embedding(label)
    out,h=model.rnn(torch.cat([inputs,emb[:,None].expand(-1,len(prefix),-1)],dim=-1))
    logits=model.head(out[:,-1])
    tokens=[]
    for _ in range(14):
        token=modal_token(logits)
        tokens.append(token[0].numpy().copy())
        out,h=model.rnn(torch.cat([token,emb],dim=1)[:,None],h)
        logits=model.head(out[:,0])
    return paths_from_tokens(prefix,np.asarray(tokens))

def build(records,seed,model=None):
    rng=random.Random(seed);dataset=Strokes(records,augment=False)
    x=[];y=[];labels=[];kinds=[]
    def add(prefix,paths,label,truth,kind):
        if sum(len(p) for p in paths)<3:return
        x.append(features(prefix,paths));y.append(truth);labels.append(label);kinds.append(kind)
    for ix in range(len(dataset)):
        seq,label,n=dataset[ix]
        if n<18:continue
        seq=seq.numpy();label=int(label)
        for cut in (max(6,int(n*.28)),max(7,int(n*.50))):
            if cut>=n-6:continue
            actual=prefix_frame(torch.from_numpy(seq)[None],cut)[0].numpy()
            prefix=actual[:cut];original=paths_from_tokens(prefix,actual[cut:min(n,cut+19)])
            if sum(len(p) for p in original)<4:continue
            add(prefix,original,label,1,"human")
            anchor=np.asarray(prefix[:,:2]).sum(axis=0)
            for kind in ("rising","flat"):
                dx=rng.uniform(.18,.46)
                dy=-rng.uniform(.14,.39) if kind=="rising" else rng.uniform(-.02,.02)
                path=[(anchor+np.array([dx,dy])*i/8).tolist() for i in range(9)]
                add(prefix,[path],label,0,kind)
            true=np.asarray(original[0])
            if len(true)>=3:
                scale=rng.uniform(2.,3.0)
                add(prefix,[[(anchor+(p-true[0])*scale).tolist() for p in true]],label,0,"overlong")
            if model is not None and ix%4==0:
                candidate=generate_bad(model,prefix,label)
                if candidate:
                    target=np.asarray(original[-1][-1]);end=np.asarray(candidate[-1][-1])
                    if np.linalg.norm(target-end)>.17:
                        add(prefix,candidate,label,0,"bad-gru")
    return np.stack(x),np.array(y,np.float32),np.array(labels,np.int64),kinds

class NeuralJudge(nn.Module):
    def __init__(self):
        super().__init__()
        self.embed=nn.Embedding(len(CHARS),8)
        self.a=nn.Linear(24,40);self.b=nn.Linear(40,16);self.out=nn.Linear(16,1)
    def forward(self,x,c):
        z=torch.cat([x,self.embed(c)],dim=-1)
        return self.out(torch.tanh(self.b(torch.tanh(self.a(z))))).squeeze(-1)

@torch.no_grad()
def predict(net,x,labels):
    net.eval()
    X=torch.from_numpy(x);C=torch.from_numpy(labels)
    return np.concatenate([torch.sigmoid(net(X[i:i+512],C[i:i+512])).numpy()
        for i in range(0,len(X),512)])

def evaluate(scores,y,kinds,threshold):
    guess=scores>=threshold;pos=y>.5
    return {"human_recall":round(float(guess[pos].mean()),5),
            "bad_rejection":round(float((~guess)[~pos].mean()),5),
            "examples":int(len(y)),
            "rising_ray_rejection":round(float((~guess)[np.array(kinds)=="rising"].mean()),5),
            "flat_tail_rejection":round(float((~guess)[np.array(kinds)=="flat"].mean()),5)}

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--epochs",type=int,default=10)
    args=parser.parse_args()
    torch.set_num_threads(4);torch.manual_seed(SEED+8731)
    rows=parse_uji(fetch_uji(".data/ujipenchars2"))
    train=[(c,p) for c,w,s,p in rows if s=="train"]
    test=[(c,w,p) for c,w,s,p in rows if s=="test"]
    writers=sorted({w for _,w,_ in test});random.Random(SEED+1784).shuffle(writers)
    midpoint=len(writers)//2
    cal=[(c,p) for c,w,p in test if w in set(writers[:midpoint])]
    hold=[(c,p) for c,w,p in test if w in set(writers[midpoint:])]
    assert len(train)>6000 and len(cal)>1100 and len(hold)>1100
    baseline=load_published("models/ink-stroke-prefix-domain-v2.json").eval()
    tx,ty,tc,tk=build(train,SEED+8732,baseline)
    cx,cy,cc,ck=build(cal,SEED+8733)
    hx,hy,hc,hk=build(hold,SEED+8734)
    print("Human trajectories and actual GRU mistakes:",len(tx),len(cx),len(hx),flush=True)
    net=NeuralJudge()
    opt=torch.optim.AdamW(net.parameters(),lr=.001,weight_decay=.0003)
    X=torch.from_numpy(tx);Y=torch.from_numpy(ty);C=torch.from_numpy(tc)
    weight=torch.where(Y>.5,3.2,1.)
    best=None;history=[];p=Path(".data/human-critic-best.pt")
    for epoch in range(args.epochs):
        net.train();idx=torch.randperm(len(X));total=0
        for batch in idx.split(512):
            z=net(X[batch],C[batch])
            loss=nn.functional.binary_cross_entropy_with_logits(z,Y[batch],
                                                                 weight=weight[batch])
            opt.zero_grad();loss.backward();opt.step();total+=float(loss)*len(batch)
        probs=predict(net,cx,cc)
        options=[]
        for cutoff in np.linspace(.10,.90,81):
            evidence=evaluate(probs,cy,ck,cutoff)
            if evidence["human_recall"]>=.90:
                options.append((evidence["bad_rejection"],cutoff,evidence))
        if options:
            quality,cutoff,evidence=max(options,key=lambda v:v[0])
            if best is None or quality>best[0]:
                best=(quality,float(cutoff),evidence,epoch+1)
                torch.save(net.state_dict(),p)
        history.append({"epoch":epoch+1,"loss":round(total/len(X),5),
          "best_calibration_rejection":round(best[0],5) if best else None})
        print("HUMAN-STROKE CRITIC:",json.dumps(history[-1]),flush=True)
    if best is None:raise RuntimeError("No threshold retained >=90% real human calibration ink")
    net.load_state_dict(torch.load(p,weights_only=True))
    hold_scores=predict(net,hx,hc)
    report=evaluate(hold_scores,hy,hk,best[1])
    focus_labels=np.isin(hc,np.array([list(CHARS).index(c) for c in "hbnmr"]))
    focus=evaluate(hold_scores[focus_labels],hy[focus_labels],
                   np.array(hk)[focus_labels],best[1])
    valid=(report["human_recall"]>=.86 and report["bad_rejection"]>=.77 and
           focus["human_recall"]>=.82 and focus["bad_rejection"]>=.74)
    metrics={"eligible":bool(valid),"threshold":best[1],
       "independent":report,"focus_independent":focus,
       "calibration":best[2],"best_epoch":best[3],"history":history,
       "real_training_glyphs":len(train),"real_heldout_writer_glyphs":len(hold),
       "source_gru":"models/ink-stroke-prefix-domain-v2.json",
       "caveat":"Human-vs-synthetic-bad-tail accuracy, not actual whole-suggestion acceptance"}
    Path("models/stroke-human-critic-v1-metrics.json").write_text(json.dumps(metrics,indent=2))
    if not valid:
        print("REJECT: learned critic cannot distinguish human motion safely",report,flush=True)
        return
    def layer(l):
        return {"weight":np.round(l.weight.detach().numpy(),6).tolist(),
                "bias":np.round(l.bias.detach().numpy(),6).tolist()}
    payload={"format":"ink-human-stroke-critic-v1","features":16,"embedding_size":8,
      "labels":list(CHARS),"threshold":best[1],
      "embedding":np.round(net.embed.weight.detach().numpy(),6).tolist(),
      "layers":[layer(net.a),layer(net.b),layer(net.out)],
      "training":{"real_uji_writers":True,"synthetic_bad_tail_negative":True,
                  "generated_gru_mistakes":True,"writer_disjoint":True},
      "metrics":report}
    Path("models/ink-human-stroke-critic-v1.json").write_text(json.dumps(payload,separators=(",",":")))
    print("ACCEPT neural human-quality critic on unseen writers:",report,flush=True)
if __name__=="__main__":main()
